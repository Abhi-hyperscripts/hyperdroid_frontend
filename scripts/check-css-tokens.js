#!/usr/bin/env node
/**
 * CSS custom-property guard
 * ----------------------------------------------------------------------------
 * Fails the build when a stylesheet reads a custom property that nothing
 * declares.
 *
 * ⭐ WHY THIS CLASS NEEDS A MACHINE. A dead token is INVISIBLE. When
 * `var(--primary-color)` resolves to nothing the declaration is invalid at
 * computed-value time and the browser DROPS IT — no error, no console warning,
 * no exception, no failing request. The element simply renders as though the
 * line had never been written, and the name looks completely correct in review.
 *
 * Measured, 2026-09-10: `--primary-color` and `--danger-color` are declared
 * nowhere in this repo, and hrms.css referenced them fifteen times. The entire
 * selected-state block for the adjustment-type cards and the tax-regime cards
 * was therefore dead: picking an option changed no border, no background and no
 * shadow, so there was no way to tell what you had selected. It shipped, and it
 * survived every review, because there is nothing to notice.
 *
 * WHAT IT DELIBERATELY DOES NOT FLAG:
 *   var(--maybe-missing, #fallback)   — a fallback means the author planned for
 *                                       absence and the page still renders. Those
 *                                       are reported as a count, never a failure.
 *
 * WHERE DECLARATIONS COUNT FROM: CSS files, <style> blocks and inline style=""
 * in HTML, and JS `setProperty('--x', …)`. Themes here are partly painted from
 * JavaScript, so ignoring that source would make this a false-positive machine
 * and it would be switched off within a day.
 *
 * The floor assertions at the bottom exist because a scanner that matches
 * nothing passes. If the regexes ever stop matching — a build step, a format
 * change — this fails loudly rather than going quietly green.
 *
 * Usage:  node scripts/check-css-tokens.js [--verbose]
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const VERBOSE = process.argv.includes('--verbose');

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.vscode', '.claude']);

// Tokens that legitimately have no declaration in this repo.
// Keep this list SHORT and justified — every entry is a hole in the guard.
const ALLOWED = new Map([
    // Tailwind's play-CDN generates these at runtime from tailwind-config.js,
    // so they are never declared in a stylesheet we own.
    ['--tw-ring-color', 'generated by the Tailwind CDN runtime'],
    ['--tw-ring-offset-width', 'generated by the Tailwind CDN runtime'],
    ['--tw-ring-offset-color', 'generated by the Tailwind CDN runtime'],
]);

function walk(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name.startsWith('.') && entry.name !== '.htaccess') continue;
        if (SKIP_DIRS.has(entry.name)) continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full, out);
        else out.push(full);
    }
    return out;
}

const files = walk(ROOT);
const cssFiles = files.filter(f => f.endsWith('.css'));
const htmlFiles = files.filter(f => f.endsWith('.html'));
const jsFiles = files.filter(f => f.endsWith('.js') && !f.includes(`${path.sep}scripts${path.sep}`));

// ── collect declarations ─────────────────────────────────────────────────
const declared = new Set();

// `--name:` at the start of a declaration. The leading delimiter keeps it from
// matching the tail of a longer token name.
//
// The quote characters matter: tokens are also set PER ELEMENT from markup, as
// style="--bc:#fff" — often built inside a JS template literal. Without " and '
// in this class those declarations are invisible and the guard reports its own
// blind spot as 62 dead tokens. Measured: --bc, --xg and --c alone accounted
// for 62 of the first run's 269 "missing" references, every one a false alarm.
const DECL = /(?:^|[;{\s"'`])(--[A-Za-z0-9_-]+)\s*:/g;
// `setProperty('--name'` / "--name" / `--name`
const JS_DECL = /setProperty\(\s*['"`](--[A-Za-z0-9_-]+)/g;

function collectDecls(text) {
    let m;
    DECL.lastIndex = 0;
    while ((m = DECL.exec(text)) !== null) declared.add(m[1]);
}

for (const f of cssFiles) collectDecls(fs.readFileSync(f, 'utf8'));
for (const f of htmlFiles) collectDecls(fs.readFileSync(f, 'utf8'));   // <style> + inline style=""
for (const f of jsFiles) {
    const text = fs.readFileSync(f, 'utf8');
    let m;
    JS_DECL.lastIndex = 0;
    while ((m = JS_DECL.exec(text)) !== null) declared.add(m[1]);
    // Stylesheets are also injected as template literals from JS in a few places.
    collectDecls(text);
}

// ── collect references ───────────────────────────────────────────────────
// Capturing the delimiter AFTER the name is what separates a bare reference
// from one with a fallback, and it survives nesting like
// color-mix(in srgb, var(--a) 8%, var(--b)) because only the next character
// after the token name is inspected.
const REF = /var\(\s*(--[A-Za-z0-9_-]+)\s*([,)])/g;

const bare = [];      // no fallback — these must resolve
let withFallback = 0;

function collectRefs(file, text) {
    const lines = text.split('\n');
    lines.forEach((line, i) => {
        let m;
        REF.lastIndex = 0;
        while ((m = REF.exec(line)) !== null) {
            if (m[2] === ',') { withFallback++; continue; }
            bare.push({ file: path.relative(ROOT, file), line: i + 1, token: m[1], text: line.trim().slice(0, 110) });
        }
    });
}

for (const f of cssFiles) collectRefs(f, fs.readFileSync(f, 'utf8'));
for (const f of htmlFiles) collectRefs(f, fs.readFileSync(f, 'utf8'));

// ── report ───────────────────────────────────────────────────────────────
const missing = bare.filter(r => !declared.has(r.token) && !ALLOWED.has(r.token));

console.log(`CSS token guard`);
console.log(`  stylesheets scanned   : ${cssFiles.length}`);
console.log(`  html files scanned    : ${htmlFiles.length}`);
console.log(`  tokens declared       : ${declared.size}`);
console.log(`  bare var() references : ${bare.length}`);
console.log(`  var() with a fallback : ${withFallback} (not checked — the fallback is the plan)`);

// ⭐ FLOORS. A scanner that matches nothing is green. If a refactor, a build
// step or a format change stops these regexes matching, fail here rather than
// silently pass and let the next dead token through.
const FLOOR_DECLARED = 200;
const FLOOR_REFS = 1000;
if (declared.size < FLOOR_DECLARED) {
    console.error(`\n✗ Only ${declared.size} declarations found (floor ${FLOOR_DECLARED}).`);
    console.error(`  The scan itself is broken — it is not finding declarations it used to.`);
    process.exit(2);
}
if (bare.length < FLOOR_REFS) {
    console.error(`\n✗ Only ${bare.length} bare var() references found (floor ${FLOOR_REFS}).`);
    console.error(`  The scan itself is broken — it is not finding references it used to.`);
    process.exit(2);
}

if (VERBOSE) {
    const byToken = {};
    bare.forEach(r => { byToken[r.token] = (byToken[r.token] || 0) + 1; });
    console.log(`\n  distinct tokens referenced: ${Object.keys(byToken).length}`);
}

const grouped = new Map();
for (const m of missing) {
    if (!grouped.has(m.token)) grouped.set(m.token, []);
    grouped.get(m.token).push(m);
}

// ── ratchet ──────────────────────────────────────────────────────────────
// There is pre-existing debt here, and failing the build on all of it would
// mean the guard is switched off on day one rather than fixed. So the baseline
// records what was already broken when this landed, and the build fails only on
// something NEW — or on an existing token getting WORSE. The count can only go
// down, never up.
const BASELINE_PATH = path.join(__dirname, 'css-token-baseline.json');
let baseline = {};
if (fs.existsSync(BASELINE_PATH)) {
    baseline = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8')).tokens || {};
}
if (process.argv.includes('--update-baseline')) {
    const tokens = {};
    [...grouped.entries()].sort().forEach(([t, hits]) => { tokens[t] = hits.length; });
    fs.writeFileSync(BASELINE_PATH, JSON.stringify({
        note: 'Undeclared CSS custom properties that already existed when the guard landed. '
            + 'The build fails on anything NOT here, or on a count that GROWS. Burn these down; '
            + 'when a token reaches zero, remove it from this file (the guard says when).',
        generated: new Date().toISOString().slice(0, 10),
        tokens
    }, null, 2) + '\n');
    console.log(`\n✓ Baseline written: ${Object.keys(tokens).length} token(s), ${missing.length} reference(s).`);
    process.exit(0);
}

const brandNew = [...grouped.entries()].filter(([t]) => !(t in baseline));
const worse = [...grouped.entries()].filter(([t, hits]) => (t in baseline) && hits.length > baseline[t]);
const fixed = Object.keys(baseline).filter(t => !grouped.has(t));
const improved = [...grouped.entries()].filter(([t, hits]) => (t in baseline) && hits.length < baseline[t]);

if (fixed.length || improved.length) {
    console.log(`\n  progress: ${fixed.length} baselined token(s) now fully resolved` +
                (improved.length ? `, ${improved.length} with fewer references` : ''));
    fixed.slice(0, 8).forEach(t => console.log(`      ${t} — gone, remove it from the baseline`));
}

if (brandNew.length === 0 && worse.length === 0) {
    console.log(`\n✓ No NEW undeclared tokens.`);
    console.log(`  ${missing.length} known reference(s) across ${grouped.size} token(s) remain as baselined debt.`);
    process.exit(0);
}

console.error(`\n✗ ${brandNew.length} new undeclared token(s)` +
              (worse.length ? ` and ${worse.length} that got worse.` : '.'));
console.error(`  A declaration reading an undeclared custom property is DROPPED by the`);
console.error(`  browser — silently. Whatever it was meant to style simply does not style.\n`);

const toReport = brandNew.concat(worse);
for (const [token, hits] of toReport.sort((a, b) => b[1].length - a[1].length)) {
    console.error(`  ${token}  — ${hits.length} reference(s)`);
    hits.slice(0, 6).forEach(h => console.error(`      ${h.file}:${h.line}  ${h.text}`));
    if (hits.length > 6) console.error(`      … and ${hits.length - 6} more`);
    console.error('');
}

console.error(`  Fix: use the real token name, or give the reference a fallback`);
console.error(`  (var(--x, <value>)) if absence is genuinely acceptable.`);
console.error(`  This is NOT baselined debt — it is new, so it is yours.`);
process.exit(1);
